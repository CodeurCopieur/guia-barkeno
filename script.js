function addHist(src,dst,from,to){
  if(!dst||/indisponible/i.test(dst))return;
  if(hist[0]&&hist[0].src===src&&hist[0].dst===dst)return;
  hist.unshift({src,dst,from,to,t:Date.now()});
  hist=hist.slice(0,HIST_MAX);
  saveHist();
  renderHist();
}

function hi(text,q){
  if(!q)return esc(text);
  const i=norm(text).indexOf(norm(q));
  if(i<0)return esc(text);
  return esc(text.slice(0,i))+"<mark>"+esc(text.slice(i,i+q.length))+"</mark>"+esc(text.slice(i+q.length));
}

function matches(theme,idx,[es,fr]){
  const key=theme+"|"+idx;
  if(state.favOnly&&!favs.has(key))return false;
  if(state.q&&!(norm(es)+" "+norm(fr)).includes(state.q))return false;
  return true;
}

function speak(btn,text){
  if(!("speechSynthesis" in window)){btn.title="Audio non disponible";return}
  window.speechSynthesis.cancel();
  document.querySelectorAll(".say.playing").forEach(b=>b.classList.remove("playing"));
  const u=new SpeechSynthesisUtterance(text.replace(/…/g,"."));
  u.lang="es-ES";u.rate=.85;
  const v=speechSynthesis.getVoices().find(v=>v.lang.toLowerCase().startsWith("es"));
  if(v)u.voice=v;
  u.onend=()=>btn.classList.remove("playing");
  btn.classList.add("playing");
  speechSynthesis.speak(u);
}

function toggleFav(key,btn){
  favs.has(key)?favs.delete(key):favs.add(key);
  saveFavs();
  btn.classList.toggle("on",favs.has(key));
}

